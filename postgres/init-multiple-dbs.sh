#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE USER ${GLITCHTIP_DB_USER} WITH PASSWORD '${GLITCHTIP_DB_PASSWORD}';
    CREATE DATABASE ${GLITCHTIP_DB_NAME} OWNER ${GLITCHTIP_DB_USER};

    CREATE USER ${FLAGSMITH_DB_USER} WITH PASSWORD '${FLAGSMITH_DB_PASSWORD}';
    CREATE DATABASE ${FLAGSMITH_DB_NAME} OWNER ${FLAGSMITH_DB_USER};

    CREATE USER ${OPENFGA_DB_USER} WITH PASSWORD '${OPENFGA_DB_PASSWORD}';
    CREATE DATABASE ${OPENFGA_DB_NAME} OWNER ${OPENFGA_DB_USER};
EOSQL
